/*
 * Computes a[i] += q if a[i] < 0.
 *
 * Vector-length agnostic: works for any VLEN. Uses register groups of 4
 * (LMUL=4). VLMAX for e32,m4 is a power of 2, so it either divides 256 or
 * exceeds it. Hence a single vsetvli with AVL = 256 yields a VL that is
 * used unchanged for every iteration.
 */

#define ptr             a0
#define count           a1
#define vl              t0
#define modulus         t1
#define stride          t2

#define data            v0
#define tmp             v4

.text
.option push
.option norvc
.option norelax
.balign 4
.global MLD_ASM_NAMESPACE(poly_caddq_riscv64_asm)
MLD_ASM_FN_SYMBOL(poly_caddq_riscv64_asm)

        li          modulus, MLDSA_Q
        li          count, MLDSA_N

        vsetvli     vl, count, e32, m4, ta, ma
        slli        stride, vl, 2

mld_poly_caddq_riscv64_loop:
        vle32.v     data, (ptr)
        vsra.vi     tmp, data, 31
        vand.vx     tmp, tmp, modulus
        vadd.vv     data, data, tmp
        vse32.v     data, (ptr)

        add         ptr, ptr, stride
        sub         count, count, vl
        bnez        count, mld_poly_caddq_riscv64_loop

        ret
.option pop

MLD_ASM_FN_SIZE(poly_caddq_riscv64_asm)

/* To facilitate single-compilation-unit (SCU) builds, undefine all macros.
