/*
 * Computes a1[i], a0[i] = decompose(a0[i]); see rv64v_decompose.inc.
 * Requires 0 <= a0[i] < q.
 *
 * Vector-length agnostic: works for any VLEN. Uses register groups of 8
 * (LMUL=8). VLMAX for e32,m8 is a power of 2, so it either divides 256 or
 * exceeds it. Hence a single vsetvli with AVL = 256 yields a VL that is
 * used unchanged for every iteration.
 */

#define a1_ptr          a0
#define a0_ptr          a1
#define count           a2
#define vl              t0
#define stride          t1
#define modulus         t2
#define c127            t3
#define half_q          t4
#define two_gamma2      t5
#define dec_mul         t6
#define dec_round       a3
#define c43             a4

#define va1             v0
#define va0             v8
#define tmp             v16

#include "rv64v_decompose.inc"

.text
.option push
.option norvc
.option norelax
.balign 4
.global MLD_ASM_NAMESPACE(poly_decompose_88_riscv64_asm)
MLD_ASM_FN_SYMBOL(poly_decompose_88_riscv64_asm)

        decompose_setup 88
        li          count, MLDSA_N

        vsetvli     vl, count, e32, m8, ta, ma
        slli        stride, vl, 2

mld_poly_decompose_88_riscv64_loop:
        vle32.v     va0, (a0_ptr)
        decompose   88, va1, va0, tmp
        vse32.v     va1, (a1_ptr)
        vse32.v     va0, (a0_ptr)

        add         a1_ptr, a1_ptr, stride
        add         a0_ptr, a0_ptr, stride
        sub         count, count, vl
        bnez        count, mld_poly_decompose_88_riscv64_loop

        ret
.option pop

MLD_ASM_FN_SIZE(poly_decompose_88_riscv64_asm)

