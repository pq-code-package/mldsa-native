/*
 * Computes a[i] = use_hint(a[i], h[i]). Requires 0 <= a[i] < q and
 * h[i] in {0, 1}. With a1, a0 = decompose(a); see rv64v_decompose.inc,
 * and d = h if a0 > 0 and d = -h otherwise:
 *
 *   r = (a1 + d) mod 16
 *
 * For h = 0, this is a1. The sign of d is computed without branches as
 * d = (h ^ n) - n with n = (a0 - 1) >> 31, which is -1 if a0 <= 0 and 0
 * otherwise.
 *
 * Vector-length agnostic: works for any VLEN. Uses register groups of 8
 * (LMUL=8). VLMAX for e32,m8 is a power of 2, so it either divides 256 or
 * exceeds it. Hence a single vsetvli with AVL = 256 yields a VL that is
 * used unchanged for every iteration.
 */

#define a_ptr           a0
#define h_ptr           a1
#define count           a2
#define vl              t0
#define stride          t1
#define modulus         t2
#define c127            t3
#define half_q          t4
#define two_gamma2      t5
#define dec_mul         t6
#define dec_round       a3
#define c43             a4

#define va1             v0
#define va0             v8
#define tmp             v16
#define vh              v24

#include "rv64v_decompose.inc"

.text
.option push
.option norvc
.option norelax
.balign 4
.global MLD_ASM_NAMESPACE(poly_use_hint_32_riscv64_asm)
MLD_ASM_FN_SYMBOL(poly_use_hint_32_riscv64_asm)

        decompose_setup 32
        li          count, MLDSA_N

        vsetvli     vl, count, e32, m8, ta, ma
        slli        stride, vl, 2

mld_poly_use_hint_32_riscv64_loop:
        vle32.v     va0, (a_ptr)
        vle32.v     vh, (h_ptr)
        decompose   32, va1, va0, tmp

        /* d = (h ^ n) - n with n = (a0 - 1) >> 31 */
        vadd.vi     va0, va0, -1
        vsra.vi     va0, va0, 31
        vxor.vv     tmp, vh, va0
        vsub.vv     tmp, tmp, va0

        /* a1 = (a1 + d) & 15 */
        vadd.vv     va1, va1, tmp
        vand.vi     va1, va1, 15
        vse32.v     va1, (a_ptr)

        add         a_ptr, a_ptr, stride
        add         h_ptr, h_ptr, stride
        sub         count, count, vl
        bnez        count, mld_poly_use_hint_32_riscv64_loop

        ret
.option pop

MLD_ASM_FN_SIZE(poly_use_hint_32_riscv64_asm)

