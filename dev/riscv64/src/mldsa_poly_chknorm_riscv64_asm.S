/*
 * Returns 0 if |a[i]| < B for all i, and 1 otherwise. Requires
 * a[i] != INT32_MIN and 0 <= B <= INT32_MAX.
 *
 * Computes the maximum of |a[i]| over all coefficients with fixed control
 * flow, and compares it with B once at the end.
 *
 * Vector-length agnostic: works for any VLEN. Uses register groups of 4
 * (LMUL=4). VLMAX for e32,m4 is a power of 2, so it either divides 256 or
 * exceeds it. Hence a single vsetvli with AVL = 256 yields a VL that is
 * used unchanged for every iteration.
 */

#define ptr             a0
#define bound           a1
#define count           a2
#define vl              t0
#define stride          t1
#define max_val         t2

#define data            v0
#define neg             v4
#define max_vec         v8
#define red             v12

.text
.option push
.option norvc
.option norelax
.balign 4
.global MLD_ASM_NAMESPACE(poly_chknorm_riscv64_asm)
MLD_ASM_FN_SYMBOL(poly_chknorm_riscv64_asm)

        li          count, MLDSA_N

        vsetvli     vl, count, e32, m4, ta, ma
        slli        stride, vl, 2
        vmv.v.i     max_vec, 0

mld_poly_chknorm_riscv64_loop:
        vle32.v     data, (ptr)
        vrsub.vi    neg, data, 0
        vmax.vv     data, data, neg
        vmaxu.vv    max_vec, max_vec, data

        add         ptr, ptr, stride
        sub         count, count, vl
        bnez        count, mld_poly_chknorm_riscv64_loop

        vmv.s.x     red, zero
        vredmaxu.vs red, max_vec, red
        vmv.x.s     max_val, red

        /* Return (max_val >= B) */
        slt         a0, max_val, bound
        xori        a0, a0, 1
        ret
.option pop

MLD_ASM_FN_SIZE(poly_chknorm_riscv64_asm)

