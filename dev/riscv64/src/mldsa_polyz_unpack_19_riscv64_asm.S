/*
 * Computes r[i] = 2^19 - x[i], where x[i] is the i-th 20-bit value of the
 * packed input; see rv64v_unpack.inc.
 *
 * Vector-length agnostic: works for any VLEN of at least 64. VLMAX for
 * e32,m2 is a power of 2 and at least 4, so it either divides 256 or
 * exceeds it. Hence a single vsetvli with AVL = 256 yields a VL that is
 * used unchanged for every iteration, and 20*VL/8 is a whole number of
 * bytes.
 */

#define out             a0
#define buf             a1
#define count           a2
#define nbytes          a3
#define vl4             a4
#define two             a5
#define gamma1          a6
#define vl              t0
#define mask            t1
#define tmp             t2
#define stride          t3

#define shifts          v4  /* register group of 2 */
#define gidx            v8  /* register group of 4 */
#define gtmp            v12 /* register group of 4 */
#define src             v16 /* register group of 2 */
#define coeffs          v20 /* register group of 2 */

#include "rv64v_unpack.inc"

.text
.option push
.option norvc
.option norelax
.balign 4
.global MLD_ASM_NAMESPACE(polyz_unpack_19_riscv64_asm)
MLD_ASM_FN_SYMBOL(polyz_unpack_19_riscv64_asm)

        li          count, MLDSA_N
        li          two, 2
        li          gamma1, (1 << 19)
        vsetvli     vl, count, e32, m2, ta, ma
        slli        stride, vl, 2
        /* nbytes = 20 * vl / 8 = 5 * vl / 2 */
        slli        nbytes, vl, 2
        add         nbytes, nbytes, vl
        srli        nbytes, nbytes, 1
        unpack_setup 20

mld_polyz_unpack_19_riscv64_loop:
        unpack      20
        vrsub.vx    coeffs, coeffs, gamma1
        vse32.v     coeffs, (out)

        add         buf, buf, nbytes
        add         out, out, stride
        sub         count, count, vl
        bnez        count, mld_polyz_unpack_19_riscv64_loop

        ret
.option pop

MLD_ASM_FN_SIZE(polyz_unpack_19_riscv64_asm)

