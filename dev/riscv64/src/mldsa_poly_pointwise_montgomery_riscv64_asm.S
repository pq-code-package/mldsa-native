/*
 * Computes a[i] = a[i] * b[i] * 2^-32 mod q with signed Montgomery
 * reduction, matching the C reference exactly; see rv64v_montgomery.inc.
 *
 * Vector-length agnostic: works for any VLEN. Uses register groups of 8
 * (LMUL=8). VLMAX for e32,m8 is a power of 2, so it either divides 256 or
 * exceeds it. Hence a single vsetvli with AVL = 256 yields a VL that is
 * used unchanged for every iteration.
 *
 * Bounds: |a|, |b| < MLD_NTT_BOUND, so |a * b| < 2^31 * q, and the result
 * is bounded by q in absolute value.
 */

#define a_ptr           a0
#define b_ptr           a1
#define count           a2
#define vl              t0
#define modulus         t1
#define qinv            t2
#define stride          t3

#define va              v0
#define vb              v8
#define prod_lo         v16
#define prod_hi         v24

#include "rv64v_montgomery.inc"

.text
.option push
.option norvc
.option norelax
.balign 4
.global MLD_ASM_NAMESPACE(poly_pointwise_montgomery_riscv64_asm)
MLD_ASM_FN_SYMBOL(poly_pointwise_montgomery_riscv64_asm)

        montgomery_setup
        li          count, MLDSA_N

        vsetvli     vl, count, e32, m8, ta, ma
        slli        stride, vl, 2

mld_poly_pointwise_montgomery_riscv64_loop:
        vle32.v     va, (a_ptr)
        vle32.v     vb, (b_ptr)
        vmul.vv     prod_lo, va, vb
        vmulh.vv    prod_hi, va, vb
        montgomery_reduce va, prod_lo, prod_hi
        vse32.v     va, (a_ptr)

        add         a_ptr, a_ptr, stride
        add         b_ptr, b_ptr, stride
        sub         count, count, vl
        bnez        count, mld_poly_pointwise_montgomery_riscv64_loop

        ret
.option pop

MLD_ASM_FN_SIZE(poly_pointwise_montgomery_riscv64_asm)

